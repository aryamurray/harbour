#!/bin/sh
# Print the Homebrew formula for one release.
#
#   render-formula.sh <version> <path to that release's SHA256SUMS>
#
# The formula installs the prebuilt release binaries; it builds nothing. The
# release workflow runs this after a release is published and commits the
# result to the tap (see .github/workflows/release.yml).

set -eu

[ $# -eq 2 ] || {
    echo "usage: $0 <version> <SHA256SUMS>" >&2
    exit 2
}
version=${1#v}
sums=$2

repo=https://github.com/aryamurray/harbour

# The checksum of one target's archive. A target missing from SHA256SUMS is
# an error: a formula with an empty sha256 would fail on a user's machine
# instead of here.
sha() {
    file="harbour-$version-$1.tar.gz"
    sum=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
    [ -n "$sum" ] || {
        echo "error: $sums has no entry for $file" >&2
        exit 1
    }
    printf '%s' "$sum"
}

url() {
    printf '%s' "$repo/releases/download/v$version/harbour-$version-$1.tar.gz"
}

mac_arm=$(sha aarch64-apple-darwin)
mac_x86=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-gnu)
linux_x86=$(sha x86_64-unknown-linux-gnu)

cat <<FORMULA
# Generated by packaging/homebrew/render-formula.sh in aryamurray/harbour.
# Do not edit: the release workflow overwrites this file.
class Harbour < Formula
  desc "Cargo-like package manager and build system for C and C++"
  homepage "$repo"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url aarch64-apple-darwin)"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$(url x86_64-apple-darwin)"
      sha256 "$mac_x86"
    end
  end

  # The Linux binaries link the system's glibc and OpenSSL 3 (libssl.so.3),
  # not Homebrew's.
  on_linux do
    on_arm do
      url "$(url aarch64-unknown-linux-gnu)"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$(url x86_64-unknown-linux-gnu)"
      sha256 "$linux_x86"
    end
  end

  def install
    bin.install "harbour"
    bin.install_symlink "harbour" => "harbor"
    generate_completions_from_executable(bin/"harbour", "completions")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/harbour --version")
    system bin/"harbour", "new", "demo"
    assert_path_exists testpath/"demo/Harbour.toml"
  end
end
FORMULA
